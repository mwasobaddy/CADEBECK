                <h2>What is PAYE?</h2>
                <p>PAYE is the system HMRC uses to collect Income Tax and National Insurance from employees' pay. As an employer, you're responsible for deducting the correct amounts and reporting them to HMRC through RTI (Real Time Information) submissions.</p>
                <h2>Key Components of PAYE</h2>
                <ul>
                    <li><strong>Tax Code</strong> — Determines how much tax-free allowance an employee has (e.g., 1257L means £12,570 tax-free)</li>
                    <li><strong>Income Tax</strong> — Basic rate (20%), higher rate (40%), or additional rate (45%)</li>
                    <li><strong>National Insurance</strong> — Class 1 NICs for employees, Class 1 Secondary for employers</li>
                    <li><strong>Student Loan Repayments</strong> — Plan 1, Plan 2, Plan 4, or Postgraduate Loan deductions</li>
                    <li><strong>Pension Contributions</strong> — Workplace pension auto-enrolment deductions</li>
                </ul>
